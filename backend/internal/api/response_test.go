func TestDecodeJSONBody_AccountIDStringOK(t *testing.T) {
	body := `{"account_id":"1-3101-2040","symbol":"SBER","board":"TQBR","side":"BUY","order_type":"LIMIT","quantity":"1","price":"400"}`
	r := httptest.NewRequest("POST", "/api/v1/orders", bytes.NewBufferString(body))
	var req orders.CreateOrderRequest
	if err := decodeJSONBody(r, &req); err != nil {
		t.Fatal(err)
	}
	if req.AccountID != "1-3101-2040" {
		t.Fatalf("got %q", req.AccountID)
	}
}

func TestDecodeJSONBody_UnknownField(t *testing.T) {
	body := `{"account_id":"1-3101-2040","symbol":"SBER","board":"TQBR","side":"BUY","order_type":"LIMIT","quantity":"1","price":"400","foo":1}`
	r := httptest.NewRequest("POST", "/api/v1/orders", bytes.NewBufferString(body))
	var req orders.CreateOrderRequest
	err := decodeJSONBody(r, &req)
	if err == nil || !strings.Contains(err.Error(), "неизвестное поле") {
		t.Fatalf("expected unknown field error, got %v", err)
	}
}

// POST /orders replies with the QUIK outcome, not with the queued order.
func TestWriteOrderAnswer(t *testing.T) {
	reason := "Недостаточно средств"
	for _, tc := range []struct {
		status     domain.OrderStatus
		reason     *string
		idempotent bool
		code       int
		want       string
	}{
		{domain.OrderAcknowledged, nil, false, 201, `"status":"ACKNOWLEDGED"`},
		{domain.OrderFilled, nil, true, 200, `"idempotent":true`},
		{domain.OrderRejected, &reason, false, 422, "rejected by QUIK: " + reason},
		{domain.OrderFailed, nil, false, 502, "ORDER_FAILED"},
		{domain.OrderQueued, nil, false, 202, "QUIK_ANSWER_PENDING"},
		{domain.OrderSent, nil, true, 202, "QUIK_ANSWER_PENDING"},
	} {
		w := httptest.NewRecorder()
		writeOrderAnswer(w, domain.Order{Status: tc.status, RejectReason: tc.reason}, tc.idempotent)
		if w.Code != tc.code || !strings.Contains(w.Body.String(), tc.want) {
			t.Fatalf("%s: %d %s", tc.status, w.Code, w.Body.String())
		}
	}
}

// client_order_id is generated by the gateway; a broker-supplied one is refused.
func TestDecodeJSONBody_ClientOrderIDRejected(t *testing.T) {
	body := `{"account_id":"1-3101-2040","client_order_id":"x","symbol":"SBER","board":"TQBR","side":"BUY","order_type":"LIMIT","quantity":"1","price":"400"}`
	r := httptest.NewRequest("POST", "/api/v1/orders", bytes.NewBufferString(body))
	var req orders.CreateOrderRequest
	if err := decodeJSONBody(r, &req); err == nil || !strings.Contains(err.Error(), "client_order_id") {
		t.Fatalf("expected client_order_id to be an unknown field, got %v", err)
	}
}
